class VoiceEngine:
    """
    Manages the Pipecat pipeline for real-time voice interaction.
    Handles Daily.co transport, OpenAI Realtime LLM, and interruption handling.
    """
    
    def __init__(self, profile: CharacterProfile):
        """
        Initialize the Voice Engine with a character profile.
        
        Args:
            profile: CharacterProfile containing all character data
        """
        self.profile = profile
        self._validate_environment()
        logger.debug(f"VoiceEngine initialized for character: {profile.name}")
    
    def _validate_environment(self) -> None:
        """Validate that all required environment variables are set."""
        required_vars = ["OPENAI_API_KEY", "DAILY_ROOM_URL"]
        missing = [var for var in required_vars if not os.getenv(var)]
        
        if missing:
            raise EnvironmentError(
                f"Missing required environment variables: {', '.join(missing)}. "
                f"Please check your .env file."
            )
        
        logger.debug("Environment variables validated")
    
    def _create_session_properties(self) -> SessionProperties:
        """
        Create OpenAI Realtime session properties with optimized settings.
        
        Returns:
            SessionProperties configured for the character
        """
        # Configure turn detection for smooth interruptions
        # SemanticTurnDetection allows natural conversation flow
        # Use a string-based eagerness to conform to pydantic expectations
        # Options: 'low', 'medium', 'high', 'auto'
        turn_detection = SemanticTurnDetection(
            eagerness="high",
            create_response=True,
            interrupt_response=True  # Allow user to interrupt AI
        )
        
        session_properties = SessionProperties(
            audio=AudioConfiguration(
                input=AudioInput(
                    transcription=InputAudioTranscription(model="whisper-1"),
                    turn_detection=turn_detection,
                    noise_reduction=InputAudioNoiseReduction(type="near_field"),
                )
            ),
            instructions=self.profile.system_prompt,
            voice=self.profile.voice.value,
            # Model configuration for better responses
            temperature=0.9,  # More creative for roleplay
            max_response_output_tokens=500,  # Reasonable response length
        )
        
        logger.debug("Session properties configured with interruption support")
        return session_properties
    
    async def run(self) -> None:
        """
        Run the voice agent pipeline.
        
        This method sets up the complete Pipecat pipeline with:
        - Daily.co transport for audio I/O
        - OpenAI Realtime for speech-to-speech
        - Context aggregation for conversation history
        """
        logger.info("Connexion au serveur vocal Daily.co...")
        
        try:
            # 1. Setup Transport (Daily.co)
            # Get token from environment, use None if empty or not set (public room)
            daily_token = os.getenv("DAILY_TOKEN", "").strip()
            if not daily_token:
                daily_token = None
                logger.info("Connexion en mode room publique (sans token)")
            
            transport = DailyTransport(
                room_url=os.getenv("DAILY_ROOM_URL"),
                token=daily_token,
                bot_name=f"Agent-{self.profile.name[:20]}",
                params=DailyParams(
                    audio_in_enabled=True,
                    audio_out_enabled=True,
                    # Note: vad_enabled is deprecated, but we keep audio_in_enabled
                    # VAD is handled by the turn_detection in session_properties
                )
            )
            logger.debug("Daily transport initialized")
            
            # 2. Setup OpenAI Realtime LLM
            session_properties = self._create_session_properties()
            
            llm = OpenAIRealtimeLLMService(
                api_key=os.getenv("OPENAI_API_KEY"),
                session_properties=session_properties,
            )
            logger.debug("OpenAI Realtime LLM service initialized")
            
            # 3. Setup Context with opening line
            initial_context = [
                {
                    "role": "user", 
                    "content": "La scène commence maintenant. Présente-toi brièvement en restant dans ton personnage."
                }
            ]
            context = LLMContext(initial_context)
            
            # 4. Create aggregators for context management
            user_aggregator, assistant_aggregator = LLMContextAggregatorPair(context)
            
            # 5. Build the pipeline
            pipeline = Pipeline([
                transport.input(),
                user_aggregator,
                llm,
                transport.output(),
                assistant_aggregator,
            ])
            
            # 6. Create task with metrics
            task = PipelineTask(
                pipeline, 
                params=PipelineParams(
                    enable_metrics=True,
                    allow_interruptions=True,  # IMPORTANT: Enable interruptions
                )
            )
            
            # 7. Setup event handlers
            @transport.event_handler("on_client_connected")
            async def on_client_connected(transport, client):
                logger.success(f"Client connecté: {client}")
                console.print(
                    Panel(
                        f"[bold green]Agent prêt![/bold green]\n"
                        f"Personnage: [cyan]{self.profile.name}[/cyan]\n"
                        f"Voix: [yellow]{self.profile.voice.value}[/yellow]",
                        title="Session Active",
                        border_style="green"
                    )
                )
            
            @transport.event_handler("on_client_disconnected")
            async def on_client_disconnected(transport, client):
                logger.info(f"Client déconnecté: {client}")
                console.print("[yellow]Session terminée.[/yellow]")
                await task.cancel()
            
            @transport.event_handler("on_error")
            async def on_error(transport, error):
                logger.error(f"Erreur de transport: {error}")
            
            # 8. Run the pipeline
            logger.info("Agent prêt. En attente de connexion...")
            runner = PipelineRunner()
            await runner.run(task)
            
        except Exception as e:
            error_str = str(e)
            logger.error(f"Erreur fatale dans le VoiceEngine: {e}")
            
            # Provide helpful error messages based on the error type
            if "invalid-token" in error_str.lower() or "unauthorized" in error_str.lower():
                console.print(
                    Panel(
                        "[bold red]Erreur d'authentification Daily.co[/bold red]\n\n"
                        "[yellow]Solutions possibles :[/yellow]\n"
                        "1. Vérifie que ta room est en mode [bold]PUBLIC[/bold] dans le dashboard Daily.co\n"
                        "   → https://dashboard.daily.co/rooms → Clique sur ta room → Privacy: Public\n\n"
                        "2. Si tu utilises une room privée, génère un nouveau token valide\n"
                        "   → Le token actuel est peut-être expiré\n\n"
                        "3. Vérifie que l'URL de la room est correcte dans .env",
                        title="Erreur de Connexion",
                        border_style="red"
                    )
                )
            elif "room" in error_str.lower() and "not found" in error_str.lower():
                console.print(
                    Panel(
                        "[bold red]Room Daily.co introuvable[/bold red]\n\n"
                        f"L'URL configurée: {os.getenv('DAILY_ROOM_URL')}\n\n"
                        "[yellow]Solutions :[/yellow]\n"
                        "1. Vérifie que la room existe dans ton dashboard Daily.co\n"
                        "2. Crée la room si elle n'existe pas: https://dashboard.daily.co/rooms",
                        title="Room Non Trouvée",
                        border_style="red"
                    )
                )
            else:
                console.print(f"[bold red]Erreur: {e}[/bold red]")
            
            raise


