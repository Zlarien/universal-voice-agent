class ImmersiveVoiceAgent:
    """
    Main application class that orchestrates all components.
    """
    
    def __init__(self):
        """Initialize the Immersive Voice Agent."""
        self.ui = TerminalUI()
        self.casting_director = None
        self.voice_engine = None
    
    def _ensure_log_directory(self) -> None:
        """Ensure the logs directory exists."""
        os.makedirs("logs", exist_ok=True)
    
    async def run(self) -> None:
        """
        Main application loop.
        """
        self._ensure_log_directory()
        
        # Display banner
        self.ui.display_banner()
        
        try:
            # Initialize casting director
            try:
                self.casting_director = CastingDirector()
            except EnvironmentError as e:
                self.ui.display_error(str(e))
                logger.error(f"Initialization failed: {e}")
                return
            
            # Get character input
            character_request = self.ui.get_character_input()
            
            if not character_request:
                self.ui.display_error("Entrée vide. Veuillez spécifier un personnage.")
                return
            
            # Get ambiance selection
            console.print()
            ambiance = self.ui.display_ambiance_menu()
            
            # Generate character profile
            try:
                profile = self.casting_director.generate_profile(
                    character_request, 
                    ambiance
                )
            except (OpenAIError, ValueError) as e:
                self.ui.display_error(f"Erreur lors de la génération du profil: {e}")
                logger.error(f"Profile generation failed: {e}")
                return
            
            # Display the profile
            self.ui.display_profile(profile)
            
            # Display connection info
            self.ui.display_connection_info()
            
            # Initialize and run voice engine
            try:
                self.voice_engine = VoiceEngine(profile)
                await self.voice_engine.run()
            except EnvironmentError as e:
                self.ui.display_error(str(e))
                logger.error(f"Voice engine initialization failed: {e}")
                return
            except Exception as e:
                self.ui.display_error(f"Erreur du moteur vocal: {e}")
                logger.error(f"Voice engine error: {e}")
                return
                
        except KeyboardInterrupt:
            logger.info("Application interrupted by user")
        finally:
            self.ui.display_goodbye()


# ============================================================================
# ENTRY POINT
# ============================================================================

def main():
    """Application entry point."""
    agent = ImmersiveVoiceAgent()
    
    try:
        asyncio.run(agent.run())
    except KeyboardInterrupt:
        pass
    except Exception as e:
        logger.exception(f"Unexpected error: {e}")
        console.print(f"[bold red]Erreur inattendue: {e}[/bold red]")
        sys.exit(1)


if __name__ == "__main__":
    main()
